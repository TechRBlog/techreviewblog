// Modal Functions for Product Blogs
function openProductBlog(productName, category) {
    const blog = productBlogs[productName];
    if (!blog) {
        alert('Review not available yet!');
        return;
    }

    // Update page title for SEO when modal opens
    const originalTitle = document.title;
    document.title = `${blog.title} | TechReview Store`;

    // Add meta description for the specific product
    let metaDesc = document.querySelector('meta[name="description"]');
    const originalDesc = metaDesc ? metaDesc.content : '';
    if (metaDesc) {
        metaDesc.content = `${blog.summary} ${productName} gaming performance, specs, price analysis and honest review.`;
    }

    document.getElementById('blogTitle').textContent = blog.title;
    document.getElementById('blogReleaseDate').textContent = `Released: ${blog.releaseDate} | Review Date: September 16, 2025`;
    document.getElementById('blogSummary').textContent = blog.summary;

    // Replace Amazon button with actual product URL if available
    let content = blog.content;
    if (blog.amazonUrl) {
        content = content.replace(/onclick="window\.open\('[^']*'/g, `onclick="window.open('${blog.amazonUrl}'`);
    }

    document.getElementById('blogContent').innerHTML = content;

    document.getElementById('productBlogModal').style.display = 'flex';
    document.body.style.overflow = 'hidden';

    // Add structured data for the specific product review
    addProductReviewStructuredData(productName, blog);

    // Store original values for restoration
    window.originalPageTitle = originalTitle;
    window.originalMetaDesc = originalDesc;
}

function closeProductBlog() {
    document.getElementById('productBlogModal').style.display = 'none';
    document.body.style.overflow = 'auto';

    // Restore original page title and meta description
    if (window.originalPageTitle) {
        document.title = window.originalPageTitle;
    }
    let metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc && window.originalMetaDesc) {
        metaDesc.content = window.originalMetaDesc;
    }

    // Remove product-specific structured data
    const existingSchema = document.querySelector('#productReviewSchema');
    if (existingSchema) {
        existingSchema.remove();
    }
}

// Add product review structured data
function addProductReviewStructuredData(productName, blog) {
    // Remove existing schema if present
    const existingSchema = document.querySelector('#productReviewSchema');
    if (existingSchema) {
        existingSchema.remove();
    }

    // Create new structured data
    const schema = {
        "@context": "https://schema.org",
        "@type": "Review",
        "itemReviewed": {
            "@type": "Product",
            "name": productName,
            "description": blog.summary,
            "brand": productName.includes('AMD') ? 'AMD' :
                    productName.includes('Intel') ? 'Intel' :
                    productName.includes('RTX') ? 'NVIDIA' : 'Unknown',
            "category": productName.includes('RTX') || productName.includes('Radeon') ? 'Graphics Cards' : 'Computer Processors'
        },
        "reviewRating": {
            "@type": "Rating",
            "ratingValue": "4.8",
            "bestRating": "5",
            "worstRating": "1"
        },
        "author": {
            "@type": "Person",
            "name": "TechReview Expert"
        },
        "publisher": {
            "@type": "Organization",
            "name": "TechReview Store"
        },
        "datePublished": "2025-09-16",
        "headline": blog.title,
        "reviewBody": blog.summary,
        "url": `https://techreviewblog.com/store-components.html#${productName.replace(/\s+/g, '-').toLowerCase()}`
    };

    const script = document.createElement('script');
    script.type = 'application/ld+json';
    script.id = 'productReviewSchema';
    script.textContent = JSON.stringify(schema);
    document.head.appendChild(script);
}

function closeProductBlog() {
    document.getElementById('productBlogModal').style.display = 'none';
    document.body.style.overflow = 'auto';
}

